- 两者都表示强烈而难以控制的感情
- 「～てしょうがない」更口语，可以用于「眠くてしょうがない」
- 「～てならない」较书面，常用于「残念でならない」「心配でならない」
- 家庭口语中直接说「寂しいです」通常更亲切；感谢信中可使用「～てならない」
